# Operators in Python
age = 50
is_young = age < 18
print("is_young:", is_young)  # False

# Comparison operators
a = True
b = False
c = a and b
print("a and b:", c)  # False(multiplication)
print("a or b:", a or b)  # True(addition)
print("not a:", not c)  # False

# Membership operators
print(type(a))  # <class 'bool'>
print(type(age))  # <class 'int'>

# Assignment operators
x=20
x += 10
print(x)

# Identity operators
y, z = 10, 20
print(y, z)  # 10 20


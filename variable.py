a = 10
b = 3

print(a + b)
print(a - b)
print(a * b)
print(a / b)    # division example: 10 / 3 = 3.3333333333333335
print(a // b)  # floor division example: 10 // 3 = 3
print(a % b)   # modulus example: 10 % 3 = 1
print(a ** b)  # exponentiation example: 10 ** 3 = 1000
print(a & b)   # bitwise AND
print(a | b)   # bitwise OR
print(a ^ b)   # bitwise XOR   
